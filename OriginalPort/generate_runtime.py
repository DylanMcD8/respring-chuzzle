#!/usr/bin/env python3
"""Ahead-of-time specialization of bundled ARM/Thumb runtime libraries.

Generate both instruction-set candidates at their respective alignments. Each
candidate is guarded by PC, instruction-set state and original instruction bytes;
only reached addresses execute. Literal pools are not claimed as executed code.
The library slides and selected ARMv7 slices match the compatibility loader.
"""
from pathlib import Path
import collections
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parent
LIBRARIES = [('libgcc_s.1.dylib', 0x30000000),
             ('libstdc++.6.0.9.dylib', 0x3748a000)]


def armv7_slice(data):
    if data[:4] == b'\xca\xfe\xba\xbe':
        for index in range(struct.unpack_from('>I', data, 4)[0]):
            cpu, subtype, offset, size, _ = struct.unpack_from('>5I', data, 8 + index * 20)
            if cpu == 12 and subtype & 0xffffff == 9:
                return data[offset:offset + size]
        raise ValueError('No ARMv7 slice')
    assert struct.unpack_from('<I', data)[0] == 0xfeedface
    assert struct.unpack_from('<II', data, 4) == (12, 9)
    return data


def code_sections(data):
    pos = 28
    for _ in range(struct.unpack_from('<I', data, 16)[0]):
        cmd, size = struct.unpack_from('<II', data, pos)
        if cmd == 1:
            for index in range(struct.unpack_from('<I', data, pos + 48)[0]):
                off = pos + 56 + 68 * index
                flags = struct.unpack_from('<I', data, off + 56)[0]
                if flags & 0x80000400:
                    name = data[off:off+16].split(b'\0')[0].decode()
                    addr, length, fileoff = struct.unpack_from('<III', data, off + 32)
                    assert fileoff + length <= len(data)
                    yield name, addr, data[fileoff:fileoff+length]
        pos += size


def write_if_changed(path, contents):
    if not path.exists() or path.read_text() != contents:
        path.write_text(contents)


def generate():
    pages = collections.defaultdict(list)
    libraries = []
    for filename, slide in LIBRARIES:
        whole = (ROOT / 'compatibility-core/touchHLE_dylibs' / filename).read_bytes()
        binary = armv7_slice(whole)
        sections = []
        for name, addr, data in code_sections(binary):
            sections.append({'name': name, 'address': hex(addr + slide), 'size': len(data)})
            for off in range((-addr) % 4, len(data) - 3, 4):
                pc = slide + addr + off
                insn = struct.unpack_from('<I', data, off)[0]
                pages[(False, pc >> 10)].append((pc, insn, 4))
            for off in range((-addr) % 2, len(data) - 1, 2):
                pc = slide + addr + off
                hw = struct.unpack_from('<H', data, off)[0]
                if hw & 0xf800 >= 0xe800:
                    if off + 4 > len(data):
                        continue
                    insn = hw << 16 | struct.unpack_from('<H', data, off + 2)[0]
                    length = 4
                else:
                    insn, length = hw, 2
                pages[(True, pc >> 10)].append((pc, insn, length))
        libraries.append({'file': filename, 'slide': hex(slide), 'slice': 'armv7',
                          'sha256': hashlib.sha256(whole).hexdigest(), 'sections': sections})
    out = ROOT / 'compatibility-core/src/cpu/interpreter/runtime_generated'
    out.mkdir(exist_ok=True)
    generated = {'mod.rs'}
    modules, dispatch = [], []
    counts = collections.Counter()
    for (thumb, page), entries in sorted(pages.items()):
        name = f'{"thumb" if thumb else "arm"}_{page:x}'
        modules.append(f'mod {name};')
        dispatch.append(f'            ({str(thumb).lower()}, 0x{page:x}) => self.runtime_{name}(mem, pc, insn),')
        lines = ['// Generated by generate_runtime.py. Do not edit.', 'use super::*;',
                 'impl InterpreterCpu {', '    #[inline(never)]',
                 f'    pub(super) fn runtime_{name}(&mut self, mem: &mut Mem, pc: u32, insn: u32) -> Option<CpuState> {{',
                 '        match (pc, insn) {']
        for pc, insn, length in entries:
            expression = (f'self.exec_native_thumb(0x{insn:08x}, {length}, 0x{pc:x}, mem)' if thumb
                          else f'self.exec_arm(0x{insn:08x}, 0x{pc:x}, mem)')
            lines.append(f'            (0x{pc:x}, 0x{insn:08x}) => {expression},')
            counts['thumb' if thumb else 'arm'] += 1
        lines += ['            _ => None,', '        }', '    }', '}']
        generated.add(f'{name}.rs')
        write_if_changed(out / f'{name}.rs', '\n'.join(lines) + '\n')
    source = ['// Generated guarded static translation of bundled runtime libraries.',
              'use super::{InterpreterCpu, Mem, CpuState};', *modules,
              'impl InterpreterCpu {',
              '    pub(super) fn runtime_native_step(&mut self, mem: &mut Mem) -> Option<CpuState> {',
              '        let pc = self.regs[15];',
              '        let thumb = self.is_thumb();',
              '        let insn = if thumb {',
              '            let hw = self.read_code_u16(mem, pc)?;',
              '            if hw & 0xf800 >= 0xe800 {',
              '                ((hw as u32) << 16) | self.read_code_u16(mem, pc.wrapping_add(2))? as u32',
              '            } else { hw as u32 }',
              '        } else { self.read_code_u32(mem, pc)? };',
              '        match (thumb, pc >> 10) {', *dispatch,
              '            _ => None,', '        }', '    }', '}']
    write_if_changed(out / 'mod.rs', '\n'.join(source) + '\n')
    for old in out.glob('*.rs'):
        if old.name not in generated:
            old.unlink()
    report = {'method': 'ahead-of-time constant-opcode specialization; no runtime code generation',
              'libraries': libraries, 'candidate_addresses': dict(counts), 'page_count': len(pages),
              'guards': ['PC', 'ARM/Thumb state', 'original instruction bytes'],
              'caveat': 'Candidates include data and alternate instruction-set interpretations; not executed-code coverage.'}
    (ROOT / 'runtime-manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k:v for k,v in report.items() if k != 'libraries'}, indent=2))

if __name__ == '__main__':
    generate()
