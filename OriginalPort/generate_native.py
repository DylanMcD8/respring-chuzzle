#!/usr/bin/env python3
"""Specialize the ARM semantics for the *original* Chuzzle game code.

This is static binary translation, not reconstructed gameplay. Rust/LLVM
partially evaluates the always-inlined instruction semantics with constant
opcodes and addresses. Generated functions become ARM64 machine code at build
time. The old iOS ABI and 32-bit data layout remain intact.

Each address checks its original word. Native ABI veneers handle dyld patches;
unrecognized code stops shipping builds. The optional interpreter is a test oracle.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess

ROOT = Path(__file__).resolve().parent
CLASSES = {'Board', 'Chuzzle', 'GameInterface', 'MainMenu', 'ChuzzleApp',
           'GameInterface_Mindbender', 'GameInterface_Zen'}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('executable', type=Path)
    parser.add_argument('--classes', help="Comma-separated original C++ classes, or '*' for all text")
    args = parser.parse_args()
    classes = set(args.classes.split(',')) if args.classes else CLASSES
    binary = args.executable.read_bytes()
    assert struct.unpack_from('<I', binary)[0] == 0xfeedface, 'Expected ARM Mach-O'
    sections = []
    pos = 28
    for _ in range(struct.unpack_from('<I', binary, 16)[0]):
        cmd, size = struct.unpack_from('<II', binary, pos)
        if cmd == 1:
            for index in range(struct.unpack_from('<I', binary, pos + 48)[0]):
                off = pos + 56 + 68 * index
                name = binary[off:off + 16].split(b'\0')[0]
                addr, length, fileoff = struct.unpack_from('<III', binary, off + 32)
                sections.append((name, addr, length, fileoff))
        pos += size
    _, start, length, offset = next(s for s in sections if s[0] == b'__text')
    nm = subprocess.check_output(['xcrun', 'nm', '-n', '-C', str(args.executable)], text=True)
    symbols = []
    for line in nm.splitlines():
        m = re.match(r'([0-9a-f]{8}) [tT] (.+)', line)
        if m and start <= int(m[1], 16) < start + length:
            symbols.append((int(m[1], 16), m[2]))
    symbols.append((start + length, '<end>'))
    pages = collections.defaultdict(list)
    functions = []
    for (addr, name), (end, _) in zip(symbols, symbols[1:]):
        if ('*' not in classes and name.split('::')[0] not in classes) or end == addr:
            continue
        functions.append({'address': hex(addr), 'end': hex(end), 'name': name})
        for pc in range(addr, end, 4):
            word = struct.unpack_from('<I', binary, offset + pc - start)[0]
            # ARM code is four-byte aligned. Thumb functions continue through
            # the fallback; data/literal pools are harmless unless branched to.
            pages[pc >> 10].append((pc, word))
    # Include all original text (even before the first named symbol) and the
    # import section, which is outside __text. Lazy linking restores these
    # LDR/branch instructions after the first call; runtime pointer data remains
    # in guest memory and is read by the specialized load semantics.
    added_sections = []
    if '*' in classes:
        pages.clear()
        for section_name, addr, size, fileoff in sections:
            if section_name != b'__text' and not section_name.startswith((b'__symbol_stub', b'__symbolstub')):
                continue
            added_sections.append({'name': section_name.decode(), 'address': hex(addr), 'size': size})
            for off in range((-addr) % 4, size - 3, 4):
                pc = addr + off
                word = struct.unpack_from('<I', binary, fileoff + off)[0]
                pages[pc >> 10].append((pc, word))
    out = ROOT / 'compatibility-core/src/cpu/interpreter/native_generated'
    out.mkdir(exist_ok=True)
    for old in out.glob('page_*.rs'):
        old.unlink()
    modules = []
    arms = []
    words = []
    for page, entries in sorted(pages.items()):
        name = f'page_{page:04x}'
        modules.append(f'mod {name};')
        arms.append(f'            0x{page:x} => self.native_{page:x}(mem, pc, word),')
        lines = ['// Generated by OriginalPort/generate_native.py. Do not edit.',
                 'use super::*;', 'impl InterpreterCpu {', '    #[inline(never)]',
                 f'    pub(super) fn native_{page:x}(&mut self, mem: &mut Mem, pc: u32, word: u32) -> Option<CpuState> {{',
                 '        match (pc, word) {']
        for pc, word in entries:
            lines.append(f'            (0x{pc:x}, 0x{word:08x}) => self.exec_arm(0x{word:08x}, 0x{pc:x}, mem),')
            words.append((pc, word))
        lines += ['            _ => None,', '        }', '    }', '}']
        (out / f'{name}.rs').write_text('\n'.join(lines) + '\n')
    source = ['// Generated static translation of the original ARMv6 game.',
              'use super::{InterpreterCpu, Mem, CpuState};', *modules,
              'impl InterpreterCpu {',
              '    pub(super) fn native_step(&mut self, mem: &mut Mem) -> Option<CpuState> {',
              '        let pc = self.regs[15];',
              '        let word = self.read_code_u32(mem, pc)?;',
              '        match pc >> 10 {', *arms, '            _ => None,', '        }', '    }', '}']
    source += ['#[cfg(test)]', 'pub(super) const NATIVE_WORDS: &[(u32,u32)] = &[']
    source += [f'    (0x{pc:x},0x{word:08x}),' for pc, word in words]
    source += ['];']
    (out / 'mod.rs').write_text('\n'.join(source) + '\n')
    report = {'method': 'ahead-of-time partial evaluation of ARM semantics',
              'original_sha256': hashlib.sha256(binary).hexdigest(),
              'classes': sorted(classes), 'function_count': len(functions),
              'translated_word_addresses': len(words), 'page_count': len(pages),
              'sections': added_sections,
              'untranslated': 'stops shipping builds; optional aot-reference interpreter for development',
              'functions': functions}
    (ROOT / 'native-manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k:v for k,v in report.items() if k != 'functions'}, indent=2))

if __name__ == '__main__':
    main()
